const RANGES: [number, number, Canton][] = PACKED.split(' ').map((run) => {
  const m = /^(\d{4})-(\d{4})([A-Z]{2})$/.exec(run)!;
  return [Number(m[1]), Number(m[2]), m[3] as Canton];
});

// The canton of a Swiss postcode, or null (unknown, or not 4 digits).
export function cantonForNpa(npa: string | null | undefined): Canton | null {
  const trimmed = (npa ?? '').trim();
  if (!/^\d{4}$/.test(trimmed)) return null;
  const n = Number(trimmed);
  for (const [from, to, canton] of RANGES) if (n >= from && n <= to) return canton;
  return null;
}
