export type ReliefCopy = Copy;
export const RELIEF_COPY: Record<ReliefLocale, Copy> = { fr, de, it };

export function reliefLocale(lang: string | undefined): ReliefLocale {
  const l = (lang ?? 'fr').slice(0, 2);
  return l === 'de' || l === 'it' ? l : 'fr';
}

export function fill(s: string, vars: Record<string, string>) {
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}
