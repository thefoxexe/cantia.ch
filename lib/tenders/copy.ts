export function useTenderCopy(): Copy {
  return COPY[getAppLocale()] ?? fr;
}

export function fill(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{\{(\w+)\}\}/g, (_, k) => String(vars[k] ?? ''));
}

