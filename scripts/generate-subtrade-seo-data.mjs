// SEO routes of the trade pages inside the non-building sectors
// (lib/site/subTrades/*.ts): title, description, FAQ and breadcrumb name,
// for FR, DE and IT. Run after editing those files:
//   node scripts/generate-subtrade-seo-data.mjs
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import ts from 'typescript';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const rootDir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');

function loadTsModule(absPath) {
  const { outputText } = ts.transpileModule(readFileSync(absPath, 'utf8'), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
  });
  const mod = { exports: {} };
  new Function('exports', 'require', 'module', '__filename', '__dirname', outputText)(mod.exports, require, mod, absPath, path.dirname(absPath));
  return mod.exports;
}

const SECTOR_SLUGS = { services: 'service-entretien', etudes: 'bureaux-etudes', creatifs: 'agences-evenementiel' };
const FILES = { services: 'SERVICES_TRADES', etudes: 'ETUDES_TRADES', creatifs: 'CREATIFS_TRADES' };
const PREFIX = { fr: '', de: 'de/', it: 'it/' };

const routes = [];
const crumbs = { fr: {}, de: {}, it: {} };
for (const [sector, exportName] of Object.entries(FILES)) {
  const file = path.join(rootDir, `lib/site/subTrades/${sector}.ts`);
  if (!existsSync(file)) continue;
  const byLocale = loadTsModule(file)[exportName];
  for (const locale of ['fr', 'de', 'it']) {
    for (const t of byLocale[locale] ?? []) {
      const bare = `metiers/${SECTOR_SLUGS[sector]}/${t.slug}`;
      const title = t.seoTitle.length <= 56 ? `${t.seoTitle} | Cantia` : t.seoTitle;
      routes.push({ path: `${PREFIX[locale]}${bare}`, title, description: t.seoDescription, faq: t.faq });
      crumbs[locale][bare] = t.name;
    }
  }
}

writeFileSync(
  path.join(rootDir, 'scripts/subtrade-seo-data.generated.mjs'),
  `// Generated by scripts/generate-subtrade-seo-data.mjs. Do not edit.\nexport const SUBTRADE_SEO = ${JSON.stringify(routes, null, 2)};\n\nexport const SUBTRADE_CRUMBS = ${JSON.stringify(crumbs, null, 2)};\n`,
);
console.log(`Generated ${routes.length} sector trade routes.`);
